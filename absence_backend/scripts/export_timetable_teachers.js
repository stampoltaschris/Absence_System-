function splitName(full) {
  const parts = full.trim().replace(/\s+/g, ' ').split(' ');
  if (parts.length < 2) return { surname: full, firstName: '' };
  const firstName = parts[parts.length - 1];
  const surname = parts.slice(0, -1).join(' ');
  return { surname, firstName };
}

function normalize(s) {
  return String(s || '')
    .normalize('NFC')
    .toUpperCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * 100% αντιστοιχία:
 * ίδιο βαπτιστικό + το πλήρες επίθετο τελειώνει στο ορατό τμήμα + μοναδικότητα
 */
function isPerfectMatch(fullName, partialVisible, allFullNames) {
  const f = splitName(normalize(fullName));
  const p = splitName(normalize(partialVisible));
  if (!f.firstName || !p.firstName) return false;
  if (f.firstName !== p.firstName) return false;

  const surF = f.surname.replace(/\s+/g, '');
  const surP = p.surname.replace(/\s+/g, '');
  if (!surP || surP.length < 3) return false;
  if (!surF.endsWith(surP)) return false;

  for (const o of allFullNames.filter((n) => n !== fullName)) {
    const os = splitName(normalize(o));
    if (
      os.firstName === f.firstName &&
      os.surname.replace(/\s+/g, '').endsWith(surP)
    ) {
      return false;
    }
  }
  return true;
}

const matched = [];
const unmatched = [];

